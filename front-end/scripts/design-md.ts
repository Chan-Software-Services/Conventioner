/**
 * The design contract (T582): writes `DESIGN.md` at the repository's root, in Google's DESIGN.md
 * format, from `src/assets/base.css` (the tokens) and `primitives.css` (the primitives).
 *
 * Agents building or reviewing a screen read it first: its YAML front matter holds every token the
 * format has a group for, and its body the rules, the other tokens' tables and every rule of
 * primitives.css no entry ends on, each section but the Do's and Don'ts linking into
 * `docs/design-system.md` for the reasons. It is generated rather than kept by hand so it cannot
 * drift from the CSS; the words the CSS cannot give live in `design-md-content.ts`. The output is
 * a pure function of those files: no date, and every list in source order.
 *
 * Run it after changing either CSS file: `npm run design-md`, then commit `DESIGN.md`.
 * `npm run design-md:check` (`--check`), which CI's frontend-lint-and-types job and
 * scripts/nm-test.sh run, fails when the committed file is not what this script writes, and when the
 * pinned `@google/design.md` linter finds an error or any warning but `orphaned-tokens`.
 * When a guard refuses (a token declared twice, a family no face loads, words naming a token or a
 * class the CSS no longer has, a component selector no rule lists, a rule of primitives.css nested
 * in another, a component font size off the type scale) it says why and writes nothing.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { lint, type Finding } from '@google/design.md/linter';
import postcss, {
  type AtRule,
  type ChildNode,
  type Container,
  type Declaration,
  type Root,
  type Rule,
} from 'postcss';

import { CONTENT, type Component, type Content } from './design-md-content.ts';

/** The three files the contract is read from, as text. */
export interface Sources {
  base: string;
  primitives: string;
  main: string;
}

/** Why the contract cannot be generated; its message is the reason, said to the developer. */
export class Refusal extends Error {}

type Group = 'colors' | 'rounded' | 'typography' | 'spacing' | 'none';

interface Token {
  /** The custom property, `--` included. */
  name: string;
  /** Its value, whitespace collapsed. */
  value: string;
  /** A comment starting on the line the declaration ends on. */
  note: string | undefined;
}

export interface Counts {
  colors: number;
  typography: number;
  rounded: number;
  spacing: number;
  components: number;
}

export interface Rendered {
  text: string;
  counts: Counts;
}

/** The format's sections, as `##` headings in its order, and the words each takes. */
const SECTIONS = [
  ['Overview', 'overview'],
  ['Colors', 'colors'],
  ['Typography', 'typography'],
  ['Layout', 'layout'],
  ['Elevation & Depth', 'elevation'],
  ['Shapes', 'shapes'],
  ['Components', 'components'],
  ["Do's and Don'ts", 'dosAndDonts'],
] as const;

type Section = (typeof SECTIONS)[number][0];

const GENERATED_LINE =
  '<!-- Generated by front-end/scripts/design-md.ts from front-end/src/assets/base.css and ' +
  'primitives.css. Never edit it by hand: change the CSS or scripts/design-md-content.ts, then run ' +
  '`npm run design-md` in front-end/. -->';

const HEX = /^#(?:[0-9a-f]{3,4}|[0-9a-f]{6}|[0-9a-f]{8})$/i;
const COLOUR_FUNCTION = /^(?:rgba?|hsla?)\(.*\)$/i;
const COLOUR_KEYWORDS = new Set(['white', 'black', 'transparent']);
const DIMENSION = /^-?(?:\d+|\d*\.\d+)(?:px|em|rem)$/;
const LONE_VAR = /^var\((--[a-z0-9-]+)\)$/i;
const TOKEN_SPAN = /^--[a-z0-9-]+$/;
const CLASSES_SPAN = /^(?:\.[a-z][\w-]*)+$/;

const collapse = (text: string) => text.replace(/\s+/g, ' ').trim();
const unquote = (family: string) => family.trim().replace(/^(['"])(.*)\1$/, '$2');

/** Every custom property of the top-level `:root` rules, in source order. */
function readTokens(base: Root): Token[] {
  const tokens: Token[] = [];
  const seen = new Set<string>();
  for (const rule of topLevelRules(base, ':root')) {
    rule.each((node) => {
      if (node.type !== 'decl' || !node.prop.startsWith('--')) return;
      if (seen.has(node.prop)) throw new Refusal(`${node.prop} is declared twice in base.css`);
      seen.add(node.prop);
      tokens.push({ name: node.prop, value: collapse(node.value), note: sameLineNote(node) });
    });
  }
  return tokens;
}

function topLevelRules(root: Root | ChildNode, selector: string): Rule[] {
  const rules: Rule[] = [];
  if ('each' in root) {
    root.each((node) => {
      if (node.type === 'rule' && node.selector === selector) rules.push(node);
    });
  }
  return rules;
}

/** The comment that starts on the line `decl` ends on: a token's figures, never its history. */
function sameLineNote(decl: Declaration): string | undefined {
  const next = decl.next();
  if (next?.type !== 'comment') return undefined;
  if (next.source?.start?.line !== decl.source?.end?.line) return undefined;
  return collapse(next.text);
}

/** Each token's group, decided by its value, the first rule that matches winning. */
function groupTokens(tokens: Token[]): Map<string, Group> {
  const byName = new Map(tokens.map((token) => [token.name, token]));
  const groups = new Map<string, Group>();
  const referenced = (value: string): Group | undefined => {
    const ref = LONE_VAR.exec(value)?.[1];
    return ref && byName.has(ref) ? groupOf(byName.get(ref)!) : undefined;
  };
  function groupOf(token: Token): Group {
    const known = groups.get(token.name);
    if (known) return known;
    groups.set(token.name, 'none'); // a reference cycle ends here rather than recursing forever
    const { name, value } = token;
    let group: Group;
    if (HEX.test(value) || COLOUR_FUNCTION.test(value) || COLOUR_KEYWORDS.has(value)) {
      group = 'colors';
    } else if (referenced(value) === 'colors') group = 'colors';
    else if (name.startsWith('--radius-')) group = 'rounded';
    else if (name.startsWith('--text-') || name === '--leading') group = 'typography';
    else if (DIMENSION.test(value) || referenced(value) === 'spacing') group = 'spacing';
    else group = 'none';
    groups.set(name, group);
    return group;
  }
  for (const token of tokens) groupOf(token);
  return groups;
}

/** The first family of `body`'s `font-family` in base.css. */
function bodyFamily(base: Root): string {
  for (const rule of topLevelRules(base, 'body')) {
    let family: string | undefined;
    rule.walkDecls('font-family', (decl) => {
      family = unquote(decl.value.split(',')[0]!);
    });
    if (family) return family;
  }
  throw new Refusal('base.css sets no font-family on body');
}

/** The families main.css loads an `@font-face` of, anywhere in it. */
function loadedFaces(main: Root): Set<string> {
  const faces = new Set<string>();
  main.walkAtRules('font-face', (face) => {
    face.walkDecls('font-family', (decl) => {
      faces.add(unquote(decl.value));
    });
  });
  return faces;
}

/** Every class named anywhere in a selector of primitives.css, `@media` included. */
function primitiveClasses(primitives: Root): Set<string> {
  const classes = new Set<string>();
  primitives.walkRules((rule) => {
    for (const [, name] of rule.selector.matchAll(/\.([a-zA-Z_][\w-]*)/g)) classes.add(name!);
  });
  return classes;
}

/**
 * Refuses a rule of primitives.css that nests a rule or an at-rule: the file writes a rule's own
 * declarations, and an at-rule's rules under its query, so what is nested would never reach it.
 */
function refuseNesting(primitives: Root): void {
  primitives.walkRules((rule) => {
    rule.each((node) => {
      if (node.type !== 'rule' && node.type !== 'atrule') return;
      const nested = node.type === 'rule' ? node.selector : `@${node.name} ${node.params}`;
      throw new Refusal(
        `${collapse(rule.selector)} in primitives.css nests ${collapse(nested)}, which DESIGN.md ` +
          'never writes: make it a rule of its own',
      );
    });
  });
}

/** Refuses when a section's words name a token base.css or a class primitives.css lacks. */
function guardWords(content: Content, tokens: Set<string>, classes: Set<string>): void {
  const words: [Section, readonly string[]][] = [
    ...SECTIONS.map(([section, key]): [Section, readonly string[]] => [section, content[key]]),
    ...content.componentGroups.map((group): [Section, readonly string[]] => [
      'Components',
      group.words,
    ]),
  ];
  for (const [section, lines] of words) {
    for (const line of lines) {
      for (const [, span] of line.matchAll(/`([^`]+)`/g)) {
        const named: [string, 'base.css' | 'primitives.css'][] = [];
        if (TOKEN_SPAN.test(span!)) named.push([span!, 'base.css']);
        for (const [, ref] of span!.matchAll(/var\((--[a-z0-9-]+)\)/gi))
          named.push([ref!, 'base.css']);
        if (CLASSES_SPAN.test(span!)) {
          for (const [, name] of span!.matchAll(/\.([a-z][\w-]*)/g)) {
            named.push([`.${name}`, 'primitives.css']);
          }
        }
        for (const [name, file] of named) {
          const has = file === 'base.css' ? tokens.has(name) : classes.has(name.slice(1));
          if (!has)
            throw new Refusal(`the words of ${section} name ${name}, which ${file} does not have`);
        }
      }
    }
  }
}

// ── Writing the file ─────────────────────────────────────────────────────────

const yamlKey = (key: string) => (/^[a-z0-9-]+$/.test(key) ? key : JSON.stringify(key));
const yamlString = (value: string) => JSON.stringify(value);
const comment = (note: string | undefined) => (note ? ` # ${note}` : '');
const cell = (text: string) => `\`${text}\``.replace(/\|/g, '\\|');

/** Each `@media` rule of base.css holding a `:root` rule: its query, and what it sets there. */
function overrides(base: Root): { params: string; decls: Declaration[] }[] {
  const found: { params: string; decls: Declaration[] }[] = [];
  base.each((node) => {
    if (node.type !== 'atrule' || node.name !== 'media') return;
    for (const rule of topLevelRules(node, ':root')) {
      const decls: Declaration[] = [];
      rule.each((child) => {
        if (child.type === 'decl') decls.push(child);
      });
      found.push({ params: collapse(node.params), decls });
    }
  });
  return found;
}

/** Each top-level rule of primitives.css under every selector its list names, in source order. */
function rulesBySelector(primitives: Root): Map<string, Rule[]> {
  const found = new Map<string, Rule[]>();
  primitives.each((node) => {
    if (node.type !== 'rule') return;
    for (const selector of node.selectors) {
      found.set(selector, [...(found.get(selector) ?? []), node]);
    }
  });
  return found;
}

/**
 * The properties CSS inherits, which alone pass from an element to one inside it: an entry such as
 * `(.note, .note a)` takes the note's ink and type, never its padding, width, corners or fill.
 * `font-weight`, and the `font` shorthand that sets one, are left out: base.css's reset gives every
 * element its own 400, so here a weight never reaches an element inside.
 */
const INHERITED = new Set([
  'color',
  'cursor',
  'direction',
  'letter-spacing',
  'line-height',
  'quotes',
  'text-align',
  'text-indent',
  'text-shadow',
  'text-transform',
  'visibility',
  'white-space',
  'word-break',
  'word-spacing',
]);
const inherits = (prop: string) =>
  INHERITED.has(prop) ||
  prop.startsWith('--') ||
  (prop.startsWith('font-') && prop !== 'font-weight') ||
  prop.startsWith('list-style');

/** Whether `inner` matches an element inside what `outer` matches: `outer`, a space or `>`, more. */
const isInside = (inner: string, outer: string) =>
  inner.startsWith(outer) && /^(?:\s+|\s*>\s*)[^\s>+~]/.test(inner.slice(outer.length));

/** A declaration's value as an entry's line writes it: whitespace collapsed, none inside brackets. */
const tidy = (value: string) => collapse(value).replace(/\(\s+/g, '(').replace(/\s+\)/g, ')');

interface Entry {
  /** The format's sub-tokens, in the format's order, each as the YAML writes its value. */
  subTokens: [string, string][];
  /** The last selector's own declarations no sub-token carries. */
  rest: Declaration[];
}

/** Renders the whole file, or refuses with the reason; nothing is written here. */
export function render(sources: Sources, content: Content = CONTENT): Rendered {
  const base = postcss.parse(sources.base, { from: 'base.css' });
  const primitives = postcss.parse(sources.primitives, { from: 'primitives.css' });
  const main = postcss.parse(sources.main, { from: 'main.css' });

  const tokens = readTokens(base);
  const groups = groupTokens(tokens);
  const values = new Map(tokens.map((token) => [token.name, token.value]));

  const faces = loadedFaces(main);
  const families = [bodyFamily(base), content.headingFamily];
  for (const family of families) {
    if (!faces.has(family)) throw new Refusal(`${family} is not a face main.css loads`);
  }
  const [textFamily, headingFamily] = families as [string, string];

  refuseNesting(primitives);
  guardWords(content, new Set(values.keys()), primitiveClasses(primitives));

  /** A lone `var()` of a grouped token is the format's reference; anything else as the CSS wrote it. */
  const valueOf = (value: string) => {
    const ref = LONE_VAR.exec(value)?.[1];
    const group = ref ? groups.get(ref) : undefined;
    return group && group !== 'none' && group !== 'typography'
      ? `{${group}.${ref!.slice(2)}}`
      : value;
  };
  const inGroup = (group: Group) => tokens.filter((token) => groups.get(token.name) === group);
  const counts: Counts = { colors: 0, typography: 0, rounded: 0, spacing: 0, components: 0 };

  const isColour = (value: string) =>
    HEX.test(value) ||
    COLOUR_FUNCTION.test(value) ||
    COLOUR_KEYWORDS.has(value) ||
    groups.get(LONE_VAR.exec(value)?.[1] ?? '') === 'colors';
  const isFill = (decl: Declaration) =>
    (decl.prop === 'background-color' || decl.prop === 'background') &&
    isColour(collapse(decl.value));
  const rules = rulesBySelector(primitives);

  /** A component's merged declarations as the format's sub-tokens, and what they leave out. */
  function entryOf(component: Component): Entry {
    const merged = new Map<string, string>();
    let fill: string | undefined;
    const ruleSets = component.selectors.map((selector) => {
      const found = rules.get(selector);
      if (!found) {
        throw new Refusal(
          `${selector} (component ${component.key} in scripts/design-md-content.ts) is in no rule of primitives.css`,
        );
      }
      return found;
    });
    // The selectors before the last step into an element inside are that element's ancestors.
    const own = component.selectors.findLastIndex(
      (selector, index) => index > 0 && isInside(selector, component.selectors[index - 1]!),
    );
    for (const [index, rule] of ruleSets.flatMap((found, index) =>
      found.map((rule) => [index, rule] as const),
    )) {
      rule.each((node) => {
        if (node.type !== 'decl') return;
        if (index < own && !inherits(node.prop)) return;
        const value = collapse(node.value);
        merged.set(node.prop, value);
        // `background: none` takes the fill away; a `background-color` that is no colour leaves it.
        if (isFill(node)) fill = value;
        else if (node.prop === 'background') fill = undefined;
      });
    }

    const carried = new Set<string>(['color', 'border-radius', 'padding', 'height', 'width']);
    const subTokens: [string, string][] = [];
    if (fill !== undefined) subTokens.push(['backgroundColor', valueOf(fill)]);
    const color = merged.get('color');
    if (color !== undefined) subTokens.push(['textColor', valueOf(color)]);

    const size = merged.get('font-size');
    if (size !== undefined) {
      const step = /^var\(--text-([a-z0-9-]+)\)$/.exec(size)?.[1];
      if (!step || !values.has(`--text-${step}`)) {
        throw new Refusal(`${component.key}'s font-size is not a --text-* token`);
      }
      const family = merged.get('font-family');
      const heading = family?.split(',').some((name) => unquote(name) === headingFamily);
      const weight = merged.get('font-weight');
      const level = heading
        ? `heading-${step}`
        : weight === '600'
          ? `text-${step}-strong`
          : `text-${step}`;
      subTokens.push(['typography', `{typography.${level}}`]);
      carried.add('font-size');
      if (heading) carried.add('font-family');
      // Only `-strong` writes a weight of its own, so a 400 stays on the entry's line and removing
      // it is drift; a heading level carries a family, never a declared weight.
      if (!heading && weight === '600') carried.add('font-weight');
    }
    for (const [prop, subToken] of [
      ['border-radius', 'rounded'],
      ['padding', 'padding'],
      ['height', 'height'],
      ['width', 'width'],
    ] as const) {
      const value = merged.get(prop);
      if (value !== undefined) subTokens.push([subToken, valueOf(value)]);
    }

    const rest: Declaration[] = [];
    for (const rule of ruleSets.at(-1)!) {
      rule.each((node) => {
        if (node.type === 'decl' && !carried.has(node.prop) && !isFill(node)) rest.push(node);
      });
    }
    return { subTokens, rest };
  }

  for (const component of content.componentEntries) {
    if (!content.componentGroups.some((group) => group.name === component.group)) {
      throw new Refusal(
        `${component.key}'s group ${component.group} has no words in scripts/design-md-content.ts`,
      );
    }
  }
  const entries = content.componentEntries.map((component): [Component, Entry] => [
    component,
    entryOf(component),
  ]);

  const yaml = [
    '---',
    'version: alpha',
    'name: Conventioner',
    `description: ${yamlString(content.description)}`,
  ];

  yaml.push('colors:');
  yaml.push(
    `  primary: ${yamlString('{colors.mm-green}')} # the format's name for --mm-green; the CSS has no --primary`,
  );
  counts.colors++;
  for (const token of inGroup('colors')) {
    yaml.push(
      `  ${yamlKey(token.name.slice(2))}: ${yamlString(valueOf(token.value))}${comment(token.note)}`,
    );
    counts.colors++;
  }

  yaml.push('typography:');
  const leading = values.get('--leading');
  for (const step of tokens.filter((token) => token.name.startsWith('--text-'))) {
    const size = step.name.slice('--text-'.length);
    const levels: [string, string, number][] = [
      [`text-${size}`, textFamily, 400],
      [`text-${size}-strong`, textFamily, 600],
      [`heading-${size}`, headingFamily, 400],
    ];
    for (const [key, family, weight] of levels) {
      yaml.push(`  ${yamlKey(key)}:`);
      yaml.push(`    fontFamily: ${yamlString(family)}`);
      yaml.push(`    fontSize: ${yamlString(step.value)}${comment(step.note)}`);
      yaml.push(`    fontWeight: ${weight}`);
      if (leading !== undefined) yaml.push(`    lineHeight: ${Number(leading)}`);
      counts.typography++;
    }
  }

  for (const group of ['rounded', 'spacing'] as const) {
    yaml.push(`${group}:`);
    for (const token of inGroup(group)) {
      yaml.push(
        `  ${yamlKey(token.name.slice(2))}: ${yamlString(valueOf(token.value))}${comment(token.note)}`,
      );
      counts[group]++;
    }
  }

  if (entries.length) yaml.push('components:');
  for (const [component, { subTokens }] of entries) {
    if (!subTokens.length) yaml.push(`  ${yamlKey(component.key)}: {}`);
    else yaml.push(`  ${yamlKey(component.key)}:`);
    for (const [subToken, value] of subTokens) {
      yaml.push(`    ${subToken}: ${yamlString(value)}`);
    }
    counts.components++;
  }
  yaml.push('---');

  // Every rule no entry ends on, and every at-rule's rules under its query, written whole, so each
  // declaration of primitives.css reaches the file and a change to any of them is drift.
  const ends = new Set(content.componentEntries.map((component) => component.selectors.at(-1)!));
  const declarationsOf = (container: Container) => {
    const shown: string[] = [];
    container.each((node) => {
      if (node.type === 'decl') shown.push(`\`${node.prop}: ${tidy(node.value)}\``);
    });
    return shown;
  };
  const ruleLine = (rule: Rule) => {
    const shown = declarationsOf(rule);
    return `- \`${tidy(rule.selector)}\`${shown.length ? `: ${shown.join(', ')}` : ''}.`;
  };
  const unshown: string[] = [];
  const queries: string[][] = [];
  function underQuery(atRule: AtRule, outer: string[]) {
    const where = [...outer, `@${atRule.name} ${collapse(atRule.params)}`];
    const own = declarationsOf(atRule);
    const lines = own.length ? [`- ${own.join(', ')}.`] : [];
    atRule.each((node) => {
      if (node.type === 'rule') lines.push(ruleLine(node));
    });
    if (lines.length) {
      queries.push([
        `Under ${where.map((query) => `\`${query}\``).join(' within ')}:`,
        '',
        ...lines,
      ]);
    }
    atRule.each((node) => {
      if (node.type === 'atrule') underQuery(node, where);
    });
  }
  primitives.each((node) => {
    if (node.type === 'rule' && !node.selectors.some((selector) => ends.has(selector))) {
      unshown.push(ruleLine(node));
    } else if (node.type === 'atrule' && !node.nodes) {
      unshown.push(`- \`@${node.name} ${collapse(node.params)}\`.`);
    } else if (node.type === 'atrule') {
      underQuery(node, []);
    }
  });

  const table = (rows: Token[]) => [
    '| Token | Value |',
    '| --- | --- |',
    ...rows.map((token) => `| ${cell(token.name)} | ${cell(token.value)} |`),
  ];
  const shadows = tokens.filter((token) => token.name.startsWith('--shadow-'));
  const ungrouped = inGroup('none').filter((token) => !token.name.startsWith('--shadow-'));

  const generated: Partial<Record<Section, string[][]>> = {
    Layout: overrides(base).map(({ params, decls }) => [
      `At \`${params}\`:`,
      '',
      '| Token | Otherwise | Here |',
      '| --- | --- | --- |',
      ...decls.map(
        (decl) =>
          `| ${cell(decl.prop)} | ${cell(values.get(decl.prop) ?? '-')} | ${cell(collapse(decl.value))} |`,
      ),
    ]),
    'Elevation & Depth': shadows.length ? [table(shadows)] : [],
    Components: [
      ...content.componentGroups.map((group) => {
        const lines = entries
          .filter(([component]) => component.group === group.name)
          .map(([component, { rest }]) => {
            const selectors = component.selectors.map((selector) => `\`${selector}\``).join(', ');
            const others = [
              ...new Set(rules.get(component.selectors.at(-1)!)!.flatMap((rule) => rule.selectors)),
            ]
              .filter((selector) => !component.selectors.includes(selector))
              .map((selector) => `\`${tidy(selector)}\``);
            const listed = others.length ? `${selectors} with ${others.join(', ')}` : selectors;
            const extra = rest.map((decl) => `\`${decl.prop}: ${tidy(decl.value)}\``).join(', ');
            return `- **\`${component.key}\`** (${listed})${extra ? `: ${extra}` : ''}.`;
          });
        return [`### ${group.name}`, '', ...group.words, ...(lines.length ? ['', ...lines] : [])];
      }),
      ['### Tokens the format has no group for', '', ...table(ungrouped)],
      ...(unshown.length || queries.length
        ? [
            [
              '### Rules no entry ends on',
              ...(unshown.length ? ['', ...unshown] : []),
              ...queries.flatMap((query) => ['', ...query]),
            ],
          ]
        : []),
    ],
  };

  const body = [GENERATED_LINE, '', "# Conventioner's design contract"];
  for (const [section, key] of SECTIONS) {
    body.push('', `## ${section}`, '', ...content[key]);
    for (const block of generated[section] ?? []) body.push('', ...block);
  }

  return { text: [...yaml, ...body].join('\n') + '\n', counts };
}

/** What `npm run design-md` prints once it has written the file. */
export function countsLine(counts: Counts): string {
  return (
    `Wrote DESIGN.md: ${counts.colors} colours, ${counts.typography} typography levels, ` +
    `${counts.rounded} rounded, ${counts.spacing} spacing, ${counts.components} components.`
  );
}

/** The three files under `frontEnd`'s `src/assets/`. */
export function readSources(frontEnd: string): Sources {
  const read = (file: string) => readFileSync(join(frontEnd, 'src/assets', file), 'utf8');
  return { base: read('base.css'), primitives: read('primitives.css'), main: read('main.css') };
}

/** Renders the whole file, then writes it to `target`; a refusal throws before anything is written. */
export function writeDesignMd(
  frontEnd: string,
  target: string,
  content: Content = CONTENT,
): string {
  const { text, counts } = render(readSources(frontEnd), content);
  writeFileSync(target, text);
  return countsLine(counts);
}

/**
 * What is wrong with the committed file against the generated one: nothing (`[]`) when they are
 * equal byte for byte, else what to run and the first line that differs.
 */
export function drift(committed: string | undefined, generated: string): string[] {
  if (committed === generated) return [];
  // Each line keeps its newline, so a missing or an extra last newline is a difference too.
  const lines = (text: string) => text.split(/(?<=\n)/);
  const want = lines(generated);
  const have = committed === undefined ? [] : lines(committed);
  let index = 0;
  while (index < want.length && index < have.length && want[index] === have[index]) index += 1;
  const shown = (all: string[]) => {
    const line = all[index];
    if (line === undefined) return '(end of file)';
    return line.endsWith('\n') ? line.slice(0, -1) : `${line} (no newline at the end of the file)`;
  };
  return [
    'DESIGN.md is not what front-end/scripts/design-md.ts writes from base.css and primitives.css: ' +
      'run `npm run design-md` in front-end/ and commit it.',
    `First difference at line ${index + 1}:`,
    `committed: ${committed === undefined ? '(no DESIGN.md)' : shown(have)}`,
    `generated: ${shown(want)}`,
  ];
}

/** The lint rule whose warnings the check lets by: most colours draw no primitive (ADR, T582). */
const ALLOWED_WARNING = 'orphaned-tokens';

/**
 * Which of the linter's findings fail the check: every error, and every warning but an
 * `orphaned-tokens` one (a warning with no rule is the parser's, and fails); info never fails.
 * The summary line always says how many warnings it let by.
 */
export function lintPolicy(findings: Finding[]): { failing: string[]; summary: string } {
  const failing: Finding[] = [];
  let allowed = 0;
  for (const finding of findings) {
    if (finding.severity === 'info') continue;
    if (finding.severity === 'warning' && finding.rule === ALLOWED_WARNING) allowed += 1;
    else failing.push(finding);
  }
  const errors = failing.filter(({ severity }) => severity === 'error').length;
  return {
    failing: failing.map(
      ({ severity, rule, path, message }) =>
        `${severity} ${rule ?? 'parser'} ${path ?? '-'}: ${message}`,
    ),
    summary:
      `DESIGN.md lint: ${errors} errors, ${failing.length - errors} warnings; ` +
      `${allowed} ${ALLOWED_WARNING} warnings allowed (colours no component uses).`,
  };
}

/**
 * `npm run design-md:check`: compares the file at `target` with what the generator writes from
 * `frontEnd`'s CSS, then lints it with the pinned linter, running both halves whenever the file
 * exists.
 */
export function checkDesignMd(
  frontEnd: string,
  target: string,
  content: Content = CONTENT,
): { ok: boolean; lines: string[] } {
  const lines: string[] = [];
  const committed = existsSync(target) ? readFileSync(target, 'utf8') : undefined;
  let ok = true;
  try {
    const stale = drift(committed, render(readSources(frontEnd), content).text);
    if (stale.length) ok = false;
    lines.push(...stale);
  } catch (error) {
    if (!(error instanceof Refusal)) throw error;
    ok = false;
    lines.push(`DESIGN.md cannot be generated: ${error.message}`);
  }
  if (committed !== undefined) {
    let findings: Finding[];
    try {
      findings = lint(committed).findings;
    } catch (error) {
      findings = [{ severity: 'error', message: `the linter could not read it: ${String(error)}` }];
    }
    const { failing, summary } = lintPolicy(findings);
    if (failing.length) ok = false;
    lines.push(...failing, summary);
  }
  return { ok, lines };
}

if (import.meta.main) {
  const frontEnd = fileURLToPath(new URL('..', import.meta.url));
  const target = join(frontEnd, '..', 'DESIGN.md');
  if (process.argv.includes('--check')) {
    const { ok, lines } = checkDesignMd(frontEnd, target);
    for (const line of lines) console.log(line);
    process.exit(ok ? 0 : 1);
  }
  try {
    console.log(writeDesignMd(frontEnd, target));
  } catch (error) {
    if (!(error instanceof Refusal)) throw error;
    console.error(`DESIGN.md not written: ${error.message}`);
    process.exit(1);
  }
}
